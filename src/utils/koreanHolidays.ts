/**
 * 날짜 문자열(YYYY-MM-DD)을 받아 대한민국 공휴일 명칭 반환 (없으면 null)
 */
export function getKoreanHoliday(dateStr: string): string | null {
  if (!dateStr) return null;

  // 1. 사전 정의된 데이터베이스 조회 (2015 ~ 2030)
  if (KOREAN_HOLIDAYS_MAP[dateStr]) {
    return KOREAN_HOLIDAYS_MAP[dateStr];
  }

  // 2. 사전에 등록되지 않은 연도에 대한 고정 양력 공휴일 fallback
  const monthDay = dateStr.slice(5); // MM-DD
  if (FIXED_ANNUAL_HOLIDAYS[monthDay]) {
    return FIXED_ANNUAL_HOLIDAYS[monthDay];
  }

  return null;
}

/**
 * 특정 날짜가 대한민국 공휴일인지 여부
 */
export function isKoreanHoliday(dateStr: string): boolean {
  return getKoreanHoliday(dateStr) !== null;
}
