import { describe, it, expect } from 'vitest';
import { politeKo } from './politeKo';

describe('politeKo', () => {
  const cases: [string, string][] = [
    ['게임을 시작한다.', '게임을 시작해요.'],
    ['귀신이 나타났다.', '귀신이 나타났어요.'],
    ['보스를 잡았습니다.', '보스를 잡았어요.'],
    ['엔딩을 봅니다.', '엔딩을 봐요.'],
    ['공포 게임입니다.', '공포 게임이에요.'],
    ['스토리 게임이다.', '스토리 게임이에요.'],
    ['비명을 지름.', '비명을 지름.'],
    ['크게 웃음.', '크게 웃음.'],
    ['결국 포기함.', '결국 포기해요.'],
    ['클리어했음!', '클리어했어요!'],
    ['밥을 먹는다.', '밥을 먹어요.'],
    ['문이 열린다', '문이 열려요'],
    ['시청자와 이야기해요.', '시청자와 이야기해요.'],
    ['좀비가 몰려온다. 도망간다!', '좀비가 몰려와요. 도망가요!'],
    ['아이템이 없다.', '아이템이 없어요.'],
    ['게임', '게임'],
    ['바다가 보인다. 바다.', '바다가 보여요. 바다.'],
    ['결과가 좋습니다.', '결과가 좋아요.'],
    ['상자가 된다.', '상자가 돼요.'],
    ['결국 엔딩을 봄.', '결국 엔딩을 봤어요.'],
    ['처음으로 돌아감.', '처음으로 돌아갔어요.'],
    ['얼굴이 바뀐 걸 알아챔', '얼굴이 바뀐 걸 알아챘어요'],
    ['새 게임.', '새 게임.'],
    ['따뜻한 봄.', '따뜻한 봄.'],
    ['무서운 장면.', '무서운 장면.'],
  ];
  it.each(cases)('%s', (a, b) => expect(politeKo(a)).toBe(b));
});
